const ENV = { vars: {}, funcs: {}, ans: 0, deg: false, grad: false, comma: true };
const close = (a, b) => Math.abs(a - b) <= 1e-9 * Math.max(1, Math.abs(b));
const check = (t, real, cx) => {
  const r = analyze(t, ENV);
  assert.equal(r.kind, "solve", t);
  assert.equal(r.roots.length, real.length, `${t}: ${JSON.stringify(r.roots)}`);
  r.roots.forEach((x, i) => assert.ok(close(x, real[i]), `${t}: ${x} ≠ ${real[i]}`));
  const s = [...r.complex].sort((a, b) => a[0] - b[0] || a[1] - b[1]);
  assert.equal(s.length, cx.length, `${t}: ${JSON.stringify(s)}`);
  s.forEach(([a, b], i) => assert.ok(close(a, cx[i][0]) && close(b, cx[i][1]), `${t}: ${a}+${b}i`));
};

